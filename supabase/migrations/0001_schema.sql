-- Cancelou: devolve as peças ao estoque. Reativou: tira de novo.
create or replace function pedidos_estoque_cancelamento() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.status = 'cancelado' and old.status <> 'cancelado' then
    update produtos p set estoque = p.estoque + i.quantidade
      from pedido_itens i
     where i.pedido_id = new.id and i.produto_id = p.id and p.estoque is not null;
  elsif old.status = 'cancelado' and new.status <> 'cancelado' then
    update produtos p set estoque = greatest(p.estoque - i.quantidade, 0)
      from pedido_itens i
     where i.pedido_id = new.id and i.produto_id = p.id and p.estoque is not null;
  end if;
  return new;
end $$;
drop trigger if exists trg_pedidos_estoque on pedidos;
create trigger trg_pedidos_estoque after update of status on pedidos
  for each row execute function pedidos_estoque_cancelamento();

